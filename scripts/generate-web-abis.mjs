// Gate 8: generates the frontend's ABI JSON files by compiling the SAME .sol source used
// for deployment -- never hand-typed, per RULES.md X6 ("do not code against a blog ABI").
// Run this whenever a contract's source changes; the output is checked-in JSON the web
// app imports directly (no solc in the browser bundle).
import { writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { compileSolidityFile } from "./lib/compile.mjs";

const outDir = fileURLToPath(new URL("../web/src/lib/abi", import.meta.url));
mkdirSync(outDir, { recursive: true });

const contracts = [
  ["AttestedCashflowRegistry", "../contracts/src/AttestedCashflowRegistry.sol"],
  ["CashflowLendingVenue", "../contracts/src/CashflowLendingVenue.sol"],
  ["MockUSDC", "../contracts/src/MockUSDC.sol"],
];

for (const [name, relPath] of contracts) {
  const { abi } = compileSolidityFile(fileURLToPath(new URL(relPath, import.meta.url)));
  // A real `as const` literal (not a JSON import + `as const` on the binding) -- viem's
  // ABI-driven type inference (function names, arg types) needs the const assertion
  // applied at the actual array literal, which a JSON import can't provide.
  const body = `// GENERATED by scripts/generate-web-abis.mjs from contracts/src/${name}.sol -- do not hand-edit.\nexport const ${name}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`;
  writeFileSync(`${outDir}/${name}.ts`, body);
  console.log(`wrote ${name}.ts (${abi.length} entries)`);
}
